// Generates spot-check.md: 10 points well inside a district (far from every Assembly and Senate
// boundary), spread across the state, with the districts our output files give for them.
//   npm run spot-check
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { BoundarySegments, DistrictIndex, OUT_FILES, ROOT, extract, polygonsOf, readGeojsonFeatures, readShapefile, SOURCES, ensureDownloads } from './lib.mjs';

const COUNT = 10;
const GRID = 40;

// Census water share per Assembly district (ALAND/AWATER attributes). CRC districts include offshore water,
// so the point search is limited to districts that are almost entirely land.
await ensureDownloads(() => {});
const water = new Map((await readShapefile(extract('census_assembly'), SOURCES.census_assembly.field))
  .map((f) => [f.district, f.properties.AWATER / (f.properties.ALAND + f.properties.AWATER)]));
const MAX_WATER_SHARE = 0.02;

const asm = readGeojsonFeatures(OUT_FILES.assembly);
const sen = readGeojsonFeatures(OUT_FILES.senate);
const asmIdx = new DistrictIndex(asm);
const senIdx = new DistrictIndex(sen);
const asmSegs = new BoundarySegments(asm);
const senSegs = new BoundarySegments(sen);

function bboxOf(f) {
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  for (const poly of polygonsOf(f.geometry)) for (const [x, y] of poly[0]) {
    minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y);
  }
  return { minX, maxX, minY, maxY };
}

// For every Assembly district, find the interior point farthest from all Assembly and Senate boundaries.
const candidates = [];
for (const f of asm) {
  const b = bboxOf(f);
  const own = new BoundarySegments([f]);
  const idx = new DistrictIndex([f]);
  const scored = [];
  for (let i = 0; i < GRID; i++) for (let j = 0; j < GRID; j++) {
    const lon = b.minX + ((i + 0.5) / GRID) * (b.maxX - b.minX);
    const lat = b.minY + ((j + 0.5) / GRID) * (b.maxY - b.minY);
    if (idx.find(lon, lat) === null) continue;
    scored.push({ lon, lat, c: own.distance(lon, lat) });
  }
  scored.sort((x, y) => y.c - x.c);
  let best = null;
  for (const p of scored.slice(0, 30)) {
    const lon = Math.round(p.lon * 1e5) / 1e5, lat = Math.round(p.lat * 1e5) / 1e5;
    const clearance = Math.min(asmSegs.distance(lon, lat), senSegs.distance(lon, lat));
    if (!best || clearance > best.clearance) best = { lon, lat, clearance, bbox: b };
  }
  candidates.push({ ...best, area: (b.maxX - b.minX) * (b.maxY - b.minY), asmDistrict: f.district });
}

// Prefer populated areas (smaller districts are denser, since districts have equal population),
// then spread across the state by farthest-point selection.
candidates.sort((a, b) => a.area - b.area);
const pool = candidates.filter((c) => water.get(c.asmDistrict) < MAX_WATER_SHARE).slice(0, 42).filter((c) => c.clearance >= 300);
const chosen = [pool.reduce((m, c) => (c.lat > m.lat ? c : m), pool[0])]; // start at the northernmost
const km = (a, b) => Math.hypot((a.lon - b.lon) * Math.cos((a.lat * Math.PI) / 180), a.lat - b.lat) * 111;
while (chosen.length < COUNT) {
  let best = null, bestD = -1;
  for (const c of pool) {
    if (chosen.includes(c)) continue;
    const d = Math.min(...chosen.map((x) => km(x, c)));
    if (d > bestD) { bestD = d; best = c; }
  }
  chosen.push(best);
}
chosen.sort((a, b) => b.lat - a.lat); // north to south

// Verify against the unsimplified CRC shapefiles too.
const rawAsm = new DistrictIndex(await readShapefile(extract('assembly'), SOURCES.assembly.field));
const rawSen = new DistrictIndex(await readShapefile(extract('senate'), SOURCES.senate.field));

const rows = chosen.map((c, i) => {
  const a = asmIdx.find(c.lon, c.lat), s = senIdx.find(c.lon, c.lat);
  if (a !== rawAsm.find(c.lon, c.lat) || s !== rawSen.find(c.lon, c.lat)) throw new Error(`spot-check point ${i + 1} disagrees with unsimplified source`);
  return `| ${i + 1} | ${c.lat.toFixed(5)} | ${c.lon.toFixed(5)} | ${a} | ${s} | ${Math.round(c.clearance)} |`;
});

const md = [
  '# Spot check',
  '',
  'Ten points for a human to verify against the Legislature\'s official lookup, https://findyourrep.legislature.ca.gov/ .',
  '',
  'How: for each row, find the street address (or drop a pin) at the latitude/longitude using any map, enter that address in the lookup, and compare the Assembly and Senate districts it reports with the last two columns. Coordinates are WGS84 decimal degrees.',
  '',
  'The points are generated by `npm run spot-check` (`spot-check.mjs`): each is the interior point of an Assembly district farthest from every Assembly and Senate boundary, taken from the smaller (denser) districts whose Census water share is under 2% (CRC districts include offshore water, so this keeps points on land) and spread across the state by farthest-point selection. The district numbers below come from the output files and were confirmed against the unsimplified CRC shapefiles. A point can still fall on a road or in a park, so choose a nearby address if needed; every point is at least the stated clearance from any boundary.',
  '',
  '| # | Latitude | Longitude | Assembly (our files) | Senate (our files) | Clearance to nearest boundary (m) |',
  '|---|---|---|---|---|---|',
  ...rows,
  '',
  'Result of the human check (fill in): ____',
  '',
].join('\n');
writeFileSync(join(ROOT, 'spot-check.md'), md);
console.log(md);
